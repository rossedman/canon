// runBuiltin runs one built-in code over every file in fsys.
func runBuiltin(t *testing.T, fsys fstest.MapFS, code string, whole bool) []Issue {
	t.Helper()
	var files []string
	for name := range fsys {
		files = append(files, name)
	}
	slices.Sort(files)
	is, err := Builtin{}.Run(context.Background(), nil, Request{FS: fsys, Files: files, Codes: []string{code}, WholeRepo: whole})
	if err != nil {
		t.Fatal(err)
	}
	return is
}

// messages joins issue messages for assertions.
func messages(is []Issue) string {
	var out []string
	for _, i := range is {
		out = append(out, fmt.Sprintf("%s:%d %s", i.Path, i.Line, i.Message))
	}
	return strings.Join(out, "\n")
}

func TestBuiltinMeta(t *testing.T) {
	t.Parallel()
	b := Builtin{}
	if b.Name() != "canon" || b.Binary() != "" || b.ConfigName() != "" || len(b.Codes()) != 11 {
		t.Fatalf("meta wrong: %v", b.Codes())
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := b.Run(ctx, nil, Request{FS: fstest.MapFS{"cmd/a.go": {}}, Files: []string{"cmd/a.go"}, Codes: []string{"one-command-per-file"}}); err == nil {
		t.Fatal("cancelled context should stop the run")
	}
	if _, err := b.Run(context.Background(), nil, Request{FS: fstest.MapFS{}, Files: []string{"cmd/a.go"}, Codes: []string{"one-command-per-file"}}); err == nil {
		t.Fatal("unreadable file should be an error")
	}
}

func TestOneCommandPerFile(t *testing.T) {
	t.Parallel()
	fsys := fstest.MapFS{
		"cmd/one.go":      {Data: []byte("var c = &cobra.Command{}")},
		"cmd/two.go":      {Data: []byte("var a = &cobra.Command{}\n\nvar b = &cobra.Command{}")},
		"cmd/none.go":     {Data: []byte("package cmd")},
		"cmd/two_test.go": {Data: []byte("&cobra.Command{} &cobra.Command{}")},
		"other/x.go":      {Data: []byte("&cobra.Command{} &cobra.Command{}")},
	}
	got := messages(runBuiltin(t, fsys, "one-command-per-file", false))
	want := "cmd/none.go:1 cmd/none.go defines 0 cobra commands; want exactly 1\ncmd/two.go:3 cmd/two.go defines 2 cobra commands; want exactly 1"
	if got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
}

func TestDocComments(t *testing.T) {
	t.Parallel()
	fsys := fstest.MapFS{
		"a/a.go":      {Data: []byte("package a\n\nfunc F() {}\n\n// G is documented.\nfunc G() {}\n\ntype T[K any] struct{}\n\nfunc (t *T[K]) M() {}\n\nfunc (T[K]) N() {}\n")},
		"a/doc.go":    {Data: []byte("// Package a has its comment here.\npackage a\n")},
		"b/b.go":      {Data: []byte("package b\n\n// F is fine.\nfunc F() {}\n")},
		"b/b_test.go": {Data: []byte("package b\nfunc TestX() {}\n")},
		"c/gen.go":    {Data: []byte("// Code generated by x. DO NOT EDIT.\n\npackage c\nfunc F() {}\n")},
		"d/broken.go": {Data: []byte("package d\nfunc {")},
		"e/e.go":      {Data: []byte("package e\n\nfunc (x) M() {}\n")},
	}
	got := messages(runBuiltin(t, fsys, "go-doc-comments", false))
	for _, want := range []string{"a/a.go:3 func F has no doc comment", "a/a.go:10 method (*T).M has no doc comment", "a/a.go:12 method (T).N has no doc comment", "b/b.go:1 package b has no package comment", "e/e.go:3 method (x).M"} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"package a has", "func G", "TestX", "c/gen.go", "d/broken.go"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("unexpected %q in\n%s", unwanted, got)
		}
	}
	if s := typeString(&ast.ArrayType{}); s != "?" {
		t.Fatalf("typeString fallback = %q", s)
	}
}

func TestUXLibraries(t *testing.T) {
	t.Parallel()
	fsys := fstest.MapFS{
		"a.go": {Data: []byte("package a\n\nimport (\n\t\"fmt\"\n\t\"github.com/fatih/color\"\n\t\"github.com/AlecAivazis/survey/v2\"\n\t\"charm.land/lipgloss/v2\"\n)\n")},
		"b.go": {Data: []byte("not go")},
	}
	got := messages(runBuiltin(t, fsys, "go-ux-libraries", false))
	if strings.Count(got, "\n") != 1 || !strings.Contains(got, "a.go:5 imports github.com/fatih/color") || !strings.Contains(got, "survey/v2") {
		t.Fatalf("got\n%s", got)
	}
}

func TestUVLock(t *testing.T) {
	t.Parallel()
	fsys := fstest.MapFS{
		"pyproject.toml":     {Data: []byte("[project]")},
		"svc/pyproject.toml": {Data: []byte("[project]")},
		"svc/uv.lock":        {Data: []byte("")},
	}
	got := messages(runBuiltin(t, fsys, "uv-lock", false))
	if got != "pyproject.toml:1 no uv.lock next to pyproject.toml; run uv lock and commit it" {
		t.Fatalf("got %s", got)
	}
}

func TestOSSFiles(t *testing.T) {
	t.Parallel()
	fsys := fstest.MapFS{"LICENSE": {}, "README.md": {}, ".github/SECURITY.md": {}, "CONTRIBUTING.md/x": {}}
	if is := runBuiltin(t, fsys, "oss-files", false); len(is) != 0 {
		t.Fatal("repo checks must not run without WholeRepo")
	}
	got := messages(runBuiltin(t, fsys, "oss-files", true))
	if got != "CONTRIBUTING.md:0 CONTRIBUTING.md is missing\nCODE_OF_CONDUCT.md:0 CODE_OF_CONDUCT.md is missing" {
		t.Fatalf("got\n%s", got)
	}
}

