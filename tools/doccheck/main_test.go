package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// write creates files under dir.
func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(dir, name)
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestCheck(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"a/a.go":      "// Package a is documented.\npackage a\n\n// F is fine.\nfunc F() {}\n\nfunc g() {}\n",
		"b/b.go":      "package b\n\nfunc (T) M() {}\n\ntype T struct{}\n",
		"b/b_test.go": "package b\n\nfunc TestX() {}\n",
		"c/gen.go":    "// Code generated by x. DO NOT EDIT.\n\npackage c\n\nfunc F() {}\n",
	})
	got, err := check([]string{dir + "/..."})
	if err != nil {
		t.Fatal(err)
	}
	text := strings.Join(got, "\n")
	for _, want := range []string{"a/a.go:7: g has no doc comment", "b/b.go:3: M has no doc comment", "package in " + filepath.ToSlash(filepath.Join(dir, "b")) + " has no package comment"} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in\n%s", want, text)
		}
	}
	if strings.Contains(text, "c/gen.go") || strings.Contains(text, "TestX") {
		t.Errorf("generated or test files reported:\n%s", text)
	}
	if _, err := check([]string{filepath.Join(dir, "missing")}); err == nil {
		t.Fatal("missing dir: want error")
	}
}

func TestRepoPasses(t *testing.T) {
	t.Chdir(filepath.Join("..", ".."))
	got, err := check([]string{"./..."})
	if err != nil || len(got) > 0 {
		t.Fatalf("repo has missing doc comments: %v %v", got, err)
	}
}
